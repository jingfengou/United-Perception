"""Generate interface documentation and an index from the actual abstract methods."""
import argparse
import dataclasses
import importlib
import inspect
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def collect():
    from up_platform.base import DeviceBackend
    from up_platform.training.base import TrainingBackend
    from up_platform.inference.base import InferenceBackend
    bases = [('device', DeviceBackend), ('training', TrainingBackend), ('inference', InferenceBackend)]
    for path in sorted((ROOT/'up_platform/ops').glob('*/base.py')):
        module = importlib.import_module(f'up_platform.ops.{path.parent.name}.base')
        base = next(value for name, value in vars(module).items() if name.endswith('Ops'))
        bases.append((path.parent.name, base))
    records = []
    for category, base in bases:
        for name in sorted(base.__abstractmethods__):
            method = getattr(base, name)
            source = Path(inspect.getfile(method)).relative_to(ROOT).as_posix()
            record = {'name': category+'.'+name, 'signature': str(inspect.signature(method)),
                      'source': source, 'line': inspect.getsourcelines(method)[1],
                      'description': inspect.getdoc(method) or ''}
            contract = getattr(method, 'contract', None)
            if contract:
                record['contract'] = dataclasses.asdict(contract)
            records.append(record)
    return records


def render(records):
    lines = ['# Platform Interfaces', '',
             'Generated by `python tools/platform_contracts.py --write`. Do not edit this file directly.', '',
             'Contracts describe required behavior, not validation claims. See [validation](VALIDATION.md).', '',
             'Ordinary PyTorch tensor storage, autograd, indexing, shape changes and scalar arithmetic are device-bridge prerequisites.',
             'For direct PyTorch bindings, dtype/layout/empty-input/error semantics are those of the installed vendor PyTorch API.',
             'Native operations retain the narrower upstream constraints below; no silent CPU fallback is allowed.', '']
    for item in records:
        lines.extend(['## '+item['name'], '', '```python', item['name']+item['signature'], '```', '', item['description'], '',
                      f"Definition: [{item['source']}:{item['line']}](../../{item['source']}#L{item['line']})", ''])
        for key, value in item.get('contract', {}).items():
            lines.append('- **'+key+'**: '+(', '.join(value) if isinstance(value, tuple) else str(value)))
        lines.append('')
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    records = collect()
    outputs = {'docs/platform/interfaces.json': json.dumps(records, indent=2)+'\n',
               'docs/platform/INTERFACES.md': render(records)}
    for name, content in outputs.items():
        path = ROOT/name
        if args.write:
            path.write_text(content, encoding='utf8', newline='\n')
        elif not path.exists() or path.read_text(encoding='utf8') != content:
            raise SystemExit(f'{name} drift; regenerate and review')
    print(json.dumps({'interfaces': len(records), 'generated_files': list(outputs)}))


if __name__ == '__main__':
    main()
